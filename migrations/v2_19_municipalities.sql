-- 自由入力の市区町村をコードに移す(city の列が残っているときだけ)。読み替え: 全角半角・空白、先頭の都道府県名、郡名、
-- ヶ/ケ・ヵ/カの揺れ。政令市の区は「中央区」だけでも、同じ都道府県に 1 つしかなければ当てる
CREATE OR REPLACE FUNCTION pg_temp.city_key(t text) RETURNS text LANGUAGE sql IMMUTABLE AS $f$
  SELECT translate(
    regexp_replace(
      regexp_replace(regexp_replace(normalize(coalesce(t, ''), NFKC), '\s', '', 'g'), '^(北海道|東京都|京都府|大阪府|.{2,3}県)', ''),
      '^[^0-9]{1,6}?郡', ''),
    'ヶヵ', 'ケカ')
$f$;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'city') THEN
    UPDATE users u SET municipality_code = hit.code
    FROM (
      SELECT u2.id, min(m.code) AS code
      FROM users u2
      JOIN municipalities m ON m.prefecture_code = u2.region_code
        AND (pg_temp.city_key(m.name) = pg_temp.city_key(u2.city)
             OR (m.kind = 'WARD' AND pg_temp.city_key(m.name) LIKE '%市' || pg_temp.city_key(u2.city)))
      WHERE u2.municipality_code IS NULL AND nullif(trim(u2.city), '') IS NOT NULL
      GROUP BY u2.id
      HAVING count(*) = 1
    ) hit
    WHERE u.id = hit.id;
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'cases' AND column_name = 'city') THEN
    UPDATE cases c SET municipality_code = hit.code
    FROM (
      SELECT c2.id, min(m.code) AS code
      FROM cases c2
      JOIN municipalities m ON m.prefecture_code = c2.region_code
        AND (pg_temp.city_key(m.name) = pg_temp.city_key(c2.city)
             OR (m.kind = 'WARD' AND pg_temp.city_key(m.name) LIKE '%市' || pg_temp.city_key(c2.city)))
      WHERE c2.municipality_code IS NULL AND nullif(trim(c2.city), '') IS NOT NULL
      GROUP BY c2.id
      HAVING count(*) = 1
    ) hit
    WHERE c.id = hit.id;
  END IF;
END;
$$;

