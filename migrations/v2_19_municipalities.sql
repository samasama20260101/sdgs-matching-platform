-- 目的: 相談者の市区町村を、自由入力(users.city・cases.city)から総務省の全国地方公共団体コードに替える。
--   - 自治体の一覧 municipalities を作って入れる(北方領土の 6 村と都道府県の行は除く。政令市の区は parent_code に市)
--   - users.municipality_code・cases.municipality_code を足す
--   - 今ある自由入力は、同じ都道府県の中で名前が 1 つにだけ当たるものをコードに移す(都道府県名・郡名の前置きと
--     政令市の市名の省略は読み替える)。当たらないものは空にする(番地まで書かれていても移さない)
--   - users.city・cases.city はここでは消さない(今動いている画面がまだ読むため)。新しい画面を出したあと v2_20 で消す
--   自治体の窓口を相談の提案に出すための土台(11/19 定例の「自治体は提案しない」の見直し)。
-- 出典: 総務省「都道府県コード及び市区町村コード」(令和6年1月1日更新、PDL1.0)
--   https://www.soumu.go.jp/denshijiti/code.html(directory-data の raw/soumu-local-gov-codes)
-- 実行場所: v2_18 のあと。Staging で確かめてから本番。何度流しても同じ結果になる(移し替えは空の行だけ。v2_20 で列を消したあとは飛ばす)。
-- 戻し方: ALTER TABLE users DROP COLUMN municipality_code; ALTER TABLE cases DROP COLUMN municipality_code; DROP TABLE municipalities;
--   (city の列は残っているので、自由入力の値はそのまま)
-- ============================================================================

